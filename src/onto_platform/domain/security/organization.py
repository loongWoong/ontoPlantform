"""Organization units and materialized org paths (design §5.1, V0.2).

An organization unit is one node of a per-workspace tree.  ``path`` is a
materialized path of the *id* chain (``/root-id/child-id/``), which means:

* a subtree is a prefix test, so row scopes such as ``org_path`` can be
  evaluated without recursive queries;
* moving a unit only rewrites that unit's ``path``, never its descendants;
* ids, not display names, are the stable identity of a node (renaming a unit
  must not silently widen a scope).

The tree is a permission input: :func:`org_path_of` feeds the
``org_path``/``org_unit`` principal attributes used by ``SecurityService``, and
a policy can grant a role on an org subtree.  An inconsistent tree (a cycle, a
cross-tenant parent, a forged path) must therefore fail closed instead of
producing a wider scope, which is why the dataclass validates its own shape
and :func:`ensure_acyclic` validates the whole tree before it is used.

No storage, clock or network access happens here; the application service
(:mod:`onto_platform.application.security.organization`) loads rows and asks
this module to build and validate the tree.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Iterable, Iterator, Mapping

from ...errors import ValidationError

#: The materialized path of "no unit".  Every real path starts and ends with
#: ``/``; ``/`` itself is reserved as the root sentinel.
ROOT_PATH = "/"

#: Display-name bound; ids are generated by the service and validated below.
MAX_UNIT_NAME_LENGTH = 128


def _require_text(value: Any, label: str) -> str:
    text = str(value or "").strip()
    if not text:
        raise ValidationError(f"{label} must not be empty")
    return text


def _validate_id(value: Any, label: str) -> str:
    text = _require_text(value, label)
    if "/" in text or text in (".", ".."):
        raise ValidationError(f"{label} contains an invalid path segment: {text!r}")
    return text


def normalize_members(members: Any) -> tuple[str, ...]:
    """Return a deduplicated tuple of user ids.

    A bare string is rejected: ``set_members(unit, "alice")`` would otherwise
    iterate characters and silently add six one-letter members.
    """
    if members is None:
        return ()
    if isinstance(members, (str, bytes)):
        raise ValidationError("organization unit members must be a list of user ids")
    try:
        values = list(members)
    except TypeError as exc:
        raise ValidationError(
            "organization unit members must be a list of user ids") from exc
    result: list[str] = []
    seen: set[str] = set()
    for member in values:
        text = _require_text(member, "organization unit member")
        if text in seen:
            continue
        seen.add(text)
        result.append(text)
    return tuple(result)


def validate_org_path(path: Any) -> str:
    """Validate the ``/a/b/`` shape and return it unchanged."""
    value = str(path or "")
    if value == ROOT_PATH:
        return ROOT_PATH
    if not value.startswith("/") or not value.endswith("/"):
        raise ValidationError(
            f"organization path must start and end with '/': {value!r}")
    segments = value[1:-1].split("/")
    if not segments or any(not segment or segment in (".", "..")
                           for segment in segments):
        raise ValidationError(f"invalid organization path: {value!r}")
    return value


def build_path(parent: "OrganizationUnit | None", unit_id: str) -> str:
    """Build the only path a unit may have: ``<parent.path><id>/``."""
    unit_id = _validate_id(unit_id, "organization unit id")
    base = ROOT_PATH if parent is None else validate_org_path(parent.path)
    return f"{base}{unit_id}/"


def path_depth(path: Any) -> int:
    """Number of units named by a path (``/`` -> 0, ``/a/b/`` -> 2)."""
    value = validate_org_path(path)
    if value == ROOT_PATH:
        return 0
    return len([segment for segment in value.strip("/").split("/") if segment])


@dataclass(slots=True)
class OrganizationUnit:
    """One node of an organization tree.

    ``path`` is server-generated: a unit's path is always its parent's path
    followed by its own id.  Constructing a unit with an inconsistent path (or
    a self-parent) raises ``ValidationError``; cross-tenant parentage is
    checked by :meth:`validate_parent` once the parent node is known.
    """

    id: str
    name: str
    parent_id: str = ""
    path: str = ROOT_PATH
    tenant_id: str = ""
    workspace_id: str = ""
    members: tuple[str, ...] = ()
    created_at: str = ""

    def __post_init__(self) -> None:
        self.id = _validate_id(self.id, "organization unit id")
        self.name = _require_text(self.name, "organization unit name")
        if len(self.name) > MAX_UNIT_NAME_LENGTH:
            raise ValidationError(
                f"organization unit name must be at most "
                f"{MAX_UNIT_NAME_LENGTH} characters")
        self.parent_id = str(self.parent_id or "").strip()
        if self.parent_id:
            self.parent_id = _validate_id(
                self.parent_id, "organization unit parent id")
            if self.parent_id == self.id:
                raise ValidationError(
                    "organization unit cannot be its own parent")
        self.path = validate_org_path(self.path or ROOT_PATH)
        self.tenant_id = str(self.tenant_id or "").strip()
        self.workspace_id = str(self.workspace_id or "").strip()
        self.members = normalize_members(self.members)
        self.created_at = str(self.created_at or "")
        # A path is never caller-supplied: it must end with this unit's parent
        # (when it has one) immediately followed by this unit's id.  A root
        # path is exactly ``/<id>/`` so a forged ancestor cannot be smuggled in.
        if self.parent_id:
            suffix = f"/{self.parent_id}/{self.id}/"
            if self.path == ROOT_PATH or not self.path.endswith(suffix):
                raise ValidationError(
                    "organization path must be generated from the parent chain")
        elif self.path != f"/{self.id}/":
            raise ValidationError(
                "organization path must be generated from the parent chain")

    # ---- tree helpers -------------------------------------------------

    def depth(self) -> int:
        return path_depth(self.path)

    def is_descendant_of(self, other: "OrganizationUnit") -> bool:
        if not other.path or other.path == ROOT_PATH or other.id == self.id:
            return False
        return self.path.startswith(other.path)

    def validate_parent(self, parent: "OrganizationUnit | None") -> None:
        """Enforce parent existence, same tenant/workspace and path origin."""
        if self.parent_id:
            if parent is None or parent.id != self.parent_id:
                raise ValidationError(
                    f"parent organization unit {self.parent_id!r} was not found")
            if (self.workspace_id and parent.workspace_id
                    and self.workspace_id != parent.workspace_id):
                raise ValidationError(
                    "parent organization unit belongs to a different workspace")
            if (self.tenant_id and parent.tenant_id
                    and self.tenant_id != parent.tenant_id):
                raise ValidationError(
                    "parent organization unit belongs to a different tenant")
            expected = build_path(parent, self.id)
        else:
            if parent is not None:
                raise ValidationError(
                    "a root organization unit must not have a parent")
            expected = build_path(None, self.id)
        if self.path != expected:
            raise ValidationError(
                "organization path must be generated from the parent path")

    # ---- serialization ------------------------------------------------

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "name": self.name,
            "parent_id": self.parent_id,
            "path": self.path,
            "tenant_id": self.tenant_id,
            "workspace_id": self.workspace_id,
            "members": list(self.members),
            "created_at": self.created_at,
        }

    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> "OrganizationUnit":
        raw_members = data.get("members")
        if isinstance(raw_members, str):
            members: tuple = (raw_members,)
        else:
            members = tuple(raw_members or ())
        return cls(
            id=str(data.get("id") or ""),
            name=str(data.get("name") or ""),
            parent_id=str(data.get("parent_id") or ""),
            path=str(data.get("path") or ROOT_PATH),
            tenant_id=str(data.get("tenant_id") or ""),
            workspace_id=str(data.get("workspace_id") or ""),
            members=members,
            created_at=str(data.get("created_at") or ""),
        )


def _coerce_units(units: Iterable[Any] | None) -> Iterator[OrganizationUnit]:
    for unit in units or ():
        yield unit if isinstance(unit, OrganizationUnit) \
            else OrganizationUnit.from_dict(unit)


def ensure_acyclic(units: Iterable[Any]) -> None:
    """Validate a whole tree: unique ids, present parents, no cycles.

    Every node's path and tenant are checked against its parent, so a row that
    was written by a buggy/older writer cannot be used to widen a scope.
    """
    items = list(_coerce_units(units))
    by_id: dict[str, OrganizationUnit] = {}
    for unit in items:
        if unit.id in by_id:
            raise ValidationError(
                f"duplicate organization unit id {unit.id!r}")
        by_id[unit.id] = unit
    # Cycle detection runs before parentage/path validation so a corrupt loop
    # is reported as a cycle rather than as an incidental path mismatch.
    for unit in items:
        seen = {unit.id}
        cursor = unit.parent_id
        while cursor:
            if cursor in seen:
                raise ValidationError(
                    f"organization unit cycle detected at {cursor!r}")
            seen.add(cursor)
            parent = by_id.get(cursor)
            if parent is None:
                raise ValidationError(
                    f"organization unit {unit.id!r} references missing parent "
                    f"{cursor!r}")
            cursor = parent.parent_id
    for unit in items:
        if unit.parent_id:
            unit.validate_parent(by_id[unit.parent_id])
        else:
            unit.validate_parent(None)


def org_units_of(units: Iterable[Any], user: str) -> list[OrganizationUnit]:
    """All units the user belongs to, deepest first ties broken by path."""
    subject = str(user or "").strip()
    if not subject:
        return []
    matched = [unit for unit in _coerce_units(units)
               if subject in unit.members]
    return sorted(matched, key=lambda unit: (path_depth(unit.path),
                                             unit.path, unit.id))


def org_unit_of(units: Iterable[Any], user: str) -> OrganizationUnit | None:
    """The deepest unit the user belongs to (longest materialized path)."""
    matched = org_units_of(units, user)
    return matched[-1] if matched else None


def org_path_of(units: Iterable[Any], user: str) -> str:
    """The ``org_path`` attribute of a user; ``""`` when they belong to none."""
    unit = org_unit_of(units, user)
    return unit.path if unit is not None else ""


def descendants_of(units: Iterable[Any],
                   unit: OrganizationUnit) -> list[OrganizationUnit]:
    """Every unit below ``unit`` (excluding itself), parents before children."""
    if not unit.path or unit.path == ROOT_PATH:
        return []
    prefix = unit.path
    return sorted(
        (candidate for candidate in _coerce_units(units)
         if candidate.id != unit.id and candidate.path.startswith(prefix)),
        key=lambda candidate: (path_depth(candidate.path), candidate.path),
    )


